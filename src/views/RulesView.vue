    <p>§ 1. Postanowienia ogólne</p> <br></br>
Niniejszy regulamin (zwany dalej „Regulaminem”) określa zasady korzystania z usług, stołów bilardowych oraz infrastruktury towarzyszącej Klubu Bilardowego Bilard (zwanego dalej „Klubem”).
Każda osoba przebywająca na terenie Klubu (zwana dalej „Klientem”) zobowiązana jest do bezwzględnego przestrzegania postanowień niniejszego Regulaminu, przepisów przeciwpożarowych oraz przepisów BHP.
Wejście na teren Klubu oraz dokonanie rezerwacji stołu jest równoznaczne z akceptacją wszystkich postanowień niniejszego Regulaminu.<p></p> <br></br>
<p>§ 2. Zasady rezerwacji i płatności</p> <br></br>
Stoły bilardowe wynajmowane są na godziny. Czas gry naliczany jest od momentu pobrania akcesoriów bilardowych (bil) do momentu ich zwrotu do recepcji lub baru Klubu.
Opłata za wynajem stołów bilardowych pobierana jest zgodnie z obowiązującym cennikiem, umieszczonym w widocznym miejscu przy recepcji/barze oraz na oficjalnej stronie internetowej Klubu.
Rezerwacji stołów można dokonywać osobiście, telefonicznie lub poprzez system rezerwacji online.
W przypadku spóźnienia się Klienta na zarezerwowany termin powyżej 15 minut, Klub zastrzega sobie prawo do anulowania rezerwacji i udostępnienia stołu innym Klientom, chyba że Klient wcześniej poinformuje obsługę o opóźnieniu.
Anulowanie rezerwacji bez ponoszenia kosztów jest możliwe najpóźniej na 24 godziny przed planowanym terminem gry.<p></p> <br></br>
<p>§ 3. Zasady korzystania ze stołów i sprzętu bilardowego</p> <br></br>
Klub oddaje do dyspozycji Klientów profesjonalny sprzęt bilardowy. Sprzęt ten należy użytkować zgodnie z jego przeznaczeniem.
W celu ochrony sukna bilardowego obowiązuje bezwzględny zakaz:
odkładania na bandy oraz sukno stołów jakichkolwiek przedmiotów (w szczególności szklanek, butelek, kieliszków, popielniczek, odzieży, toreb);
spożywania posiłków oraz napojów bezpośrednio przy stołach bilardowych (do tego celu wyznaczone są stoliki kawiarniane/barowe);
siadania, opierania się całą masą ciała lub kładzenia się na stołach bilardowych;
wykonywania uderzeń pionowych (tzw. masé) oraz skoków (jump shot) przez osoby nieposiadające odpowiednich umiejętności, o ile obsługa uzna, że grozi to uszkodzeniem sukna.
Kredowanie kija bilardowego powinno odbywać się poza obszarem sukna stołu, w sposób zapobiegający osypywaniu się pyłu na stół.
Po zakończeniu gry Klient zobowiązany jest do niezwłocznego zwrotu kompletnego zestawu bil oraz kijów bilardowych pracownikowi obiektu.<p></p> <br></br>
<p>§ 4. Odpowiedzialność materialna</p> <br></br>
Klienci ponoszą pełną odpowiedzialność materialną za szkody wyrządzone na terenie Klubu, w tym za zniszczenie lub uszkodzenie mienia, sprzętu bilardowego, elementów wyposażenia czy wnętrza obiektu.
W przypadku uszkodzenia sukna bilardowego (np. rozcięcie, przypalenie, trwałe zabrudzenie), Klient zobowiązany jest do pokrycia pełnego kosztu wymiany sukna na nowe (wraz z kosztem usługi serwisowej) według wyceny przedstawionej przez managera Klubu.
Za szkody wyrządzone przez osoby niepełnoletnie pełną odpowiedzialność materialną ponoszą ich rodzice lub opiekunowie prawni.<p></p> <br></br>
<p>§ 5. Porządek i zasady zachowania</p> <br></br>
Na terenie Klubu obowiązuje kulturalne zachowanie. Zabrania się używania wulgaryzmów, krzyków oraz zachowań powszechnie uznawanych za obraźliwe lub zakłócające spokój innych Klientów.
Obsługa Klubu ma prawo odmówić wstępu lub nakazać opuszczenie lokalu osobom:
których stan wskazuje na znaczne spożycie alkoholu lub środków odurzających;
zachowującym się agresywnie lub stwarzającym zagrożenie dla innych osób oraz mienia;
których ubiór lub higiena osobista naruszają ogólnie przyjęte normy społeczne.
Na terenie całego Klubu obowiązuje całkowity zakaz palenia wyrobów tytoniowych oraz papierosów elektronicznych, poza miejscami do tego wyraźnie wyznaczonymi.
Wnoszenie na teren Klubu własnych napojów (w tym alkoholowych) oraz artykułów spożywczych bez uprzedniej zgody managera lokalu jest surowo zabronione.<p></p> <br></br>
<p>§ 6. Postanowienia końcowe</p> <br></br>
Klub nie ponosi odpowiedzialności za rzeczy osobiste, wartościowe oraz odzież pozostawioną przez Klientów bez nadzoru na terenie obiektu.
Osoby nieprzestrzegające postanowień niniejszego Regulaminu mogą zostać wyproszone z Klubu bez prawa do zwrotu kosztów za niewykorzystany czas rezerwacji stołu.
W sprawach nieuregulowanych niniejszym Regulaminem mają zastosowanie odpowiednie przepisy Kodeksu Cywilnego.
Regulamin wchodzi w życie z dniem opublikowania i jest dostępny do wglądu w recepcji Klubu oraz na stronie internetowej.<br></br>
